CREATE OR REPLACE FUNCTION public.search_verified_jobs(
  p_query text DEFAULT NULL,
  p_country text DEFAULT NULL,
  p_city text DEFAULT NULL,
  p_job_type text DEFAULT NULL,
  p_employment_type text DEFAULT NULL,
  p_work_mode text DEFAULT NULL,
  p_experience_min numeric DEFAULT NULL,
  p_experience_max numeric DEFAULT NULL,
  p_sort text DEFAULT 'relevance',
  p_limit integer DEFAULT 25,
  p_offset integer DEFAULT 0
)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public, pg_temp
AS $function$
  WITH parameters AS (
    SELECT
      nullif(trim(p_query), '') AS query_text,
      CASE WHEN nullif(trim(p_query), '') IS NULL THEN NULL
        ELSE websearch_to_tsquery('simple', p_query)
      END AS query_terms,
      least(greatest(coalesce(p_limit, 25), 1), 50) AS result_limit,
      greatest(coalesce(p_offset, 0), 0) AS result_offset
  ),
  filtered AS MATERIALIZED (
    SELECT
      jobs.id,
      jobs.source_id,
      jobs.company_id,
      jobs.external_job_id,
      jobs.company_name,
      jobs.company_website,
      jobs.title,
      jobs.description,
      jobs.location_text,
      jobs.city,
      jobs.state,
      jobs.country,
      jobs.job_type,
      jobs.employment_type,
      jobs.work_mode,
      jobs.experience_min_years,
      jobs.experience_max_years,
      jobs.experience_text,
      jobs.salary_text,
      jobs.eligibility_text,
      jobs.graduation_year,
      jobs.internship_duration,
      jobs.posted_at,
      jobs.application_deadline,
      jobs.last_verified_at,
      jobs.application_url,
      jobs.change_status,
      CASE WHEN parameters.query_terms IS NULL THEN 0::real
        ELSE ts_rank(jobs.search_document, parameters.query_terms)
      END AS relevance
    FROM public.jobs AS jobs
    CROSS JOIN parameters
    WHERE jobs.is_verified
      AND jobs.status = 'active'
      AND jobs.last_verified_at >= now() - interval '7 days'
      AND jobs.application_url IS NOT NULL
      AND (parameters.query_terms IS NULL OR jobs.search_document @@ parameters.query_terms)
      AND (nullif(trim(p_country), '') IS NULL OR lower(jobs.country) = lower(trim(p_country)))
      AND (nullif(trim(p_city), '') IS NULL OR jobs.location_text ILIKE '%' || trim(p_city) || '%')
      AND (nullif(trim(p_job_type), '') IS NULL OR jobs.job_type = p_job_type)
      AND (nullif(trim(p_employment_type), '') IS NULL OR jobs.employment_type = p_employment_type)
      AND (nullif(trim(p_work_mode), '') IS NULL OR jobs.work_mode = p_work_mode)
      AND (
        p_experience_max IS NULL
        OR (
          jobs.experience_min_years IS NOT NULL
          AND jobs.experience_min_years <= p_experience_max
          AND (jobs.experience_max_years IS NULL OR jobs.experience_max_years >= coalesce(p_experience_min, 0))
        )
      )
  ),
  result_page AS (
    SELECT filtered.*
    FROM filtered
    CROSS JOIN parameters
    ORDER BY
      CASE WHEN p_sort = 'newest' THEN filtered.posted_at END DESC NULLS LAST,
      CASE WHEN p_sort = 'verified' THEN filtered.last_verified_at END DESC NULLS LAST,
      CASE WHEN p_sort NOT IN ('newest', 'verified') THEN filtered.relevance END DESC,
      filtered.posted_at DESC NULLS LAST,
      filtered.last_verified_at DESC
    LIMIT (SELECT result_limit FROM parameters)
    OFFSET (SELECT result_offset FROM parameters)
  )
  SELECT jsonb_build_object(
    'total', (SELECT count(*) FROM filtered),
    'items', coalesce(
      (SELECT jsonb_agg(to_jsonb(result_page) - 'relevance') FROM result_page),
      '[]'::jsonb
    )
  );
$function$;

